// ValidateConfig rejects the built-in marker in tags - see abac.RejectBuiltInTag.
func (r *BiotAbacConditionResource) ValidateConfig(ctx context.Context, req resource.ValidateConfigRequest, resp *resource.ValidateConfigResponse) {
	var config TerraformAbacCondition

	resp.Diagnostics.Append(req.Config.Get(ctx, &config)...)
	if resp.Diagnostics.HasError() {
		return
	}

	abac.RejectBuiltInTag(config.Tags, Entity, &resp.Diagnostics)
}

func (r *BiotAbacConditionResource) Create(ctx context.Context, req resource.CreateRequest, resp *resource.CreateResponse) {
	var plan TerraformAbacCondition

	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	if resp.Diagnostics.HasError() {
		return
	}

	createRequest, diags := MapTerraformConditionToCreateRequest(ctx, plan)
	resp.Diagnostics.Append(diags...)
	if resp.Diagnostics.HasError() {
		return
	}

	response, err := r.client.Abac.CreateCondition(ctx, createRequest)
	if err != nil {
		abac.AddError(&resp.Diagnostics, Entity, "create", plan.ID.ValueString(), err)
		return
	}

	model, diags := MapConditionResponseToTerraformModel(ctx, response)
	resp.Diagnostics.Append(diags...)
	if resp.Diagnostics.HasError() {
		return
	}

	resp.Diagnostics.Append(resp.State.Set(ctx, model)...)
}

func (r *BiotAbacConditionResource) Read(ctx context.Context, req resource.ReadRequest, resp *resource.ReadResponse) {
	var state TerraformAbacCondition

	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}

	response, err := r.client.Abac.GetCondition(ctx, state.ID.ValueString())
	if err != nil {
		if transport.IsNotFound(err) {
			// Gone from the backend - drop it from state so Terraform plans a create.
			resp.State.RemoveResource(ctx)
			return
		}
		abac.AddError(&resp.Diagnostics, Entity, "read", state.ID.ValueString(), err)
		return
	}

	model, diags := MapConditionResponseToTerraformModel(ctx, response)
	resp.Diagnostics.Append(diags...)
	if resp.Diagnostics.HasError() {
		return
	}

	resp.Diagnostics.Append(resp.State.Set(ctx, model)...)
}

func (r *BiotAbacConditionResource) Update(ctx context.Context, req resource.UpdateRequest, resp *resource.UpdateResponse) {
	var plan TerraformAbacCondition

	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	if resp.Diagnostics.HasError() {
		return
	}

	updateRequest, diags := MapTerraformConditionToUpdateRequest(ctx, plan)
	resp.Diagnostics.Append(diags...)
	if resp.Diagnostics.HasError() {
		return
	}

	response, err := r.client.Abac.UpdateCondition(ctx, plan.ID.ValueString(), updateRequest)
	if err != nil {
		abac.AddError(&resp.Diagnostics, Entity, "update", plan.ID.ValueString(), err)
		return
	}

	model, diags := MapConditionResponseToTerraformModel(ctx, response)
	resp.Diagnostics.Append(diags...)
	if resp.Diagnostics.HasError() {
		return
	}

	resp.Diagnostics.Append(resp.State.Set(ctx, model)...)
}

func (r *BiotAbacConditionResource) Delete(ctx context.Context, req resource.DeleteRequest, resp *resource.DeleteResponse) {
	var state TerraformAbacCondition

	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}

	err := r.client.Abac.DeleteCondition(ctx, state.ID.ValueString())
	if err != nil {
		if transport.IsNotFound(err) {
			// Already gone - deleting it is exactly what we wanted.
			return
		}
		abac.AddError(&resp.Diagnostics, Entity, "delete", state.ID.ValueString(), err)
	}
}

// Conditions are imported by their id, which is the same id used in the configuration.
func (r *BiotAbacConditionResource) ImportState(ctx context.Context, req resource.ImportStateRequest, resp *resource.ImportStateResponse) {
	resource.ImportStatePassthroughID(ctx, path.Root("id"), req, resp)
}
