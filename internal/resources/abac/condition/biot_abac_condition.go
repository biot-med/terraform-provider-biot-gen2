var (
	_ resource.Resource                   = &BiotAbacConditionResource{}
	_ resource.ResourceWithConfigure      = &BiotAbacConditionResource{}
	_ resource.ResourceWithImportState    = &BiotAbacConditionResource{}
	_ resource.ResourceWithValidateConfig = &BiotAbacConditionResource{}
)

// Entity describes conditions to the shared abac helpers.
var Entity = abac.Entity{
	Noun:                    "condition",
	ResourceType:            "biot_abac_condition",
	AlreadyExistsCode:       "CONDITION_ALREADY_EXISTS",
	NotFoundCode:            "CONDITIONS_NOT_FOUND",
	InvalidValueCode:        "INVALID_CONDITION_VALUE",
	CannotDeleteBuiltInCode: "CANNOT_DELETE_BUILTIN_CONDITION",
}

func NewResource() resource.Resource {
	return &BiotAbacConditionResource{}
}

type BiotAbacConditionResource struct {
	client *api.APIClient
}

func (r *BiotAbacConditionResource) Metadata(ctx context.Context, req resource.MetadataRequest, resp *resource.MetadataResponse) {
	resp.TypeName = "biot_abac_condition"
}

// The response of this function is passed to every condition resource when running
// create / read / update / delete. The input is the return of the ProviderConfigure function.
func (r *BiotAbacConditionResource) Configure(ctx context.Context, req resource.ConfigureRequest, resp *resource.ConfigureResponse) {
	if req.ProviderData == nil {
		return
	}

	client, ok := req.ProviderData.(*api.APIClient)
	if !ok {
		resp.Diagnostics.AddError("Unexpected Provider Data Type", "Expected *api.APIClient")
		return
	}

	r.client = client
}

